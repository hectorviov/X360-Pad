static inline uint8_t ds4_stick(const uint8_t *p, int invert) {   // signed 16-bit (y up) -> 0..255, 128 centred (y down when inverted)
    int v = (int16_t)(p[0] | p[1] << 8);
    if (invert) v = -v - 1;
    return (uint8_t)((v + 32768) >> 8);
}

/// The 20-byte wired-controller report (X360Wire.h) as DualShock 4 input report 0x01; buttons by position (A cross, B circle, X square, Y triangle).
static inline void ds4_from_x360(uint8_t r[DS4_INPUT_LEN], const uint8_t *w, uint8_t counter, uint16_t ts, uint8_t click) {
    for (int i = 0; i < DS4_INPUT_LEN; i++) r[i] = 0;
    uint8_t b0 = w[2], b1 = w[3];
    r[0] = 0x01;
    r[1] = ds4_stick(w + 6, 0); r[2] = ds4_stick(w + 8, 1); r[3] = ds4_stick(w + 10, 0); r[4] = ds4_stick(w + 12, 1);
    int x = !!(b0 & 0x08) - !!(b0 & 0x04), y = !!(b0 & 0x02) - !!(b0 & 0x01);
    static const uint8_t hat[3][3] = {{7, 0, 1}, {6, 8, 2}, {5, 4, 3}};
    r[5] = hat[y + 1][x + 1];
    if (b1 & 0x40) r[5] |= 0x10;   // X: square
    if (b1 & 0x10) r[5] |= 0x20;   // A: cross
    if (b1 & 0x20) r[5] |= 0x40;   // B: circle
    if (b1 & 0x80) r[5] |= 0x80;   // Y: triangle
    if (b1 & 0x01) r[6] |= 0x01;   // LB: L1
    if (b1 & 0x02) r[6] |= 0x02;   // RB: R1
    if (w[4] > click) r[6] |= 0x04;   // L2 pressed past the click level
    if (w[5] > click) r[6] |= 0x08;
    if (b0 & 0x20) r[6] |= 0x10;   // Back: Share
    if (b0 & 0x10) r[6] |= 0x20;   // Start: Options
    if (b0 & 0x40) r[6] |= 0x40;   // L3
    if (b0 & 0x80) r[6] |= 0x80;   // R3
    r[7] = (uint8_t)((counter & 0x3f) << 2) | ((b1 & 0x04) ? 0x01 : 0);   // Guide: PS
    r[8] = w[4]; r[9] = w[5];
    r[10] = (uint8_t)ts; r[11] = (uint8_t)(ts >> 8);
    r[20] = 0x20;                  // accelerometer: 1 g on y (at rest, face up), 8192 per g
    r[30] = 0x1A;                  // battery 10 of 10, cable connected
    r[35] = 0x80; r[39] = 0x80;    // no finger on the touchpad
}

/// Output report 0x05 (32 bytes with its ID): byte 4 the right (weak) motor, 5 the left (strong). Returns 0 for another report.
static inline int ds4_rumble(const uint8_t *d, uint64_t n, uint8_t *strong, uint8_t *weak) {
    if (n >= 6 && d[0] == 0x05) { *weak = d[4]; *strong = d[5]; return 1; }
    return 0;
}
